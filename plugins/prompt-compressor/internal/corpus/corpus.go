// Package corpus generates and loads the Prompt Compressor test corpus in
// testdata/corpus: real-shaped LLM request bodies in every vendor format the
// gateway proxies, carrying realistic tool output (test runs, build logs,
// kubectl, terraform, diffs, searches, listings, JSON, CSV, HTML, MCP), plus
// 30-turn agent sessions stored as the full body of every turn.
//
// Everything is synthetic and deterministic: each entry is seeded from its
// name, so `go generate ./internal/corpus` rewrites the same bytes, and
// TestCorpusMatchesGenerator fails when the files and the generator drift.
// See testdata/corpus/README.md for the layout and provenance.
package corpus

//go:generate go run ./cmd/corpusgen -out ../../testdata/corpus

import (
	"bufio"
	"bytes"
	"compress/gzip"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"runtime"
)

// ManifestVersion is bumped when the manifest's fields change meaning.
const ManifestVersion = 1

// Dir returns the corpus directory of this module (for tests).
func Dir() string {
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		panic("corpus: cannot locate source file")
	}
	return filepath.Join(filepath.Dir(file), "..", "..", "testdata", "corpus")
}

// NewEntry wraps a request body that is not part of the corpus (a captured
// body a customer replays) as an entry the corpus tools accept. It expects
// extraction; tools skip it when the format has no extractor.
func NewEntry(name, format, path string, body []byte) Entry {
	return Entry{Name: name, Format: format, Path: path, Expect: ExpectExtract, ToolPairing: "unknown", body: body}
}

// Body returns the entry's request body, byte for byte.
func (e Entry) Body() []byte { return e.body }

// Bodies returns the session's request bodies, turn by turn.
func (s Session) Bodies() [][]byte { return s.bodies }

// Readable reports whether a segmenter is expected to read the entry today:
// it expects extraction and no bead it waits on is pending, or the pending
// format is now supported (supported tells).
func (e Entry) Readable(supported func(format string) bool) bool {
	return e.Expect == ExpectExtract && (e.Pending == "" || supported(e.Format))
}

// Build generates the corpus in memory.
func Build() Manifest {
	return Manifest{
		Version:  ManifestVersion,
		Note:     "Generated by internal/corpus (go generate ./internal/corpus). Synthetic data only; see README.md.",
		Entries:  Entries(),
		Sessions: Sessions(),
	}
}

// Write writes m to dir: manifest.json, bodies/ and sessions/. It removes
// bodies and sessions the manifest no longer lists.
func Write(dir string, m Manifest) error {
	for _, sub := range []string{"bodies", "sessions"} {
		if err := os.RemoveAll(filepath.Join(dir, sub)); err != nil {
			return err
		}
	}
	for _, e := range m.Entries {
		if err := writeFile(filepath.Join(dir, e.File), e.body); err != nil {
			return err
		}
	}
	for _, s := range m.Sessions {
		if err := writeFile(filepath.Join(dir, s.File), encodeSession(s.bodies)); err != nil {
			return err
		}
	}
	raw, err := json.MarshalIndent(m, "", "  ")
	if err != nil {
		return err
	}
	return writeFile(filepath.Join(dir, "manifest.json"), append(raw, '\n'))
}

func writeFile(path string, data []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, data, 0o644)
}

// Load reads the corpus in dir.
func Load(dir string) (Manifest, error) {
	var m Manifest
	raw, err := os.ReadFile(filepath.Join(dir, "manifest.json"))
	if err != nil {
		return m, err
	}
	if err := json.Unmarshal(raw, &m); err != nil {
		return m, fmt.Errorf("corpus: manifest: %w", err)
	}
	if m.Version != ManifestVersion {
		return m, fmt.Errorf("corpus: manifest version %d, want %d", m.Version, ManifestVersion)
	}
	for i := range m.Entries {
		e := &m.Entries[i]
		if e.body, err = os.ReadFile(filepath.Join(dir, e.File)); err != nil {
			return m, err
		}
	}
	for i := range m.Sessions {
		s := &m.Sessions[i]
		if s.bodies, err = readSession(filepath.Join(dir, s.File)); err != nil {
			return m, fmt.Errorf("corpus: %s: %w", s.Name, err)
		}
	}
	return m, nil
}

// A session file is gzip over one line per turn: the number of leading
// bytes the turn shares with the previous turn's body, a tab, and the rest
// of the body. Full-history turns share almost everything with the turn
// before, which gzip's 32 KiB window cannot see across 100 KiB bodies, so
// the prefix sharing keeps 30 full bodies to a few hundred KiB. Bodies are
// compact JSON and hold no raw newline. `corpusgen -explode` writes every
// turn out as its own file for reading.

func encodeSession(bodies [][]byte) []byte {
	var buf bytes.Buffer
	zw, err := gzip.NewWriterLevel(&buf, gzip.BestCompression)
	if err != nil {
		panic(err)
	}
	var prev []byte
	for _, b := range bodies {
		if bytes.IndexByte(b, '\n') >= 0 {
			panic("corpus: session body holds a newline")
		}
		n := commonPrefix(prev, b)
		fmt.Fprintf(zw, "%d\t", n)
		zw.Write(b[n:])
		zw.Write([]byte{'\n'})
		prev = b
	}
	if err := zw.Close(); err != nil {
		panic(err)
	}
	return buf.Bytes()
}

func commonPrefix(a, b []byte) int {
	n := min(len(a), len(b))
	for i := 0; i < n; i++ {
		if a[i] != b[i] {
			return i
		}
	}
	return n
}

func readSession(path string) ([][]byte, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	zr, err := gzip.NewReader(f)
	if err != nil {
		return nil, err
	}
	return decodeSession(bufio.NewReaderSize(zr, 1<<20))
}

func decodeSession(r *bufio.Reader) ([][]byte, error) {
	var bodies [][]byte
	var prev []byte
	for {
		line, err := r.ReadBytes('\n')
		if err == io.EOF && len(line) == 0 {
			return bodies, nil
		}
		if err != nil {
			return nil, fmt.Errorf("turn %d: %w", len(bodies)+1, err)
		}
		line = line[:len(line)-1]
		tab := bytes.IndexByte(line, '\t')
		var n int
		if tab < 0 {
			return nil, fmt.Errorf("turn %d: no prefix length", len(bodies)+1)
		}
		if _, err := fmt.Sscanf(string(line[:tab]), "%d", &n); err != nil || n < 0 || n > len(prev) {
			return nil, fmt.Errorf("turn %d: bad prefix length %q", len(bodies)+1, line[:tab])
		}
		body := append(append([]byte(nil), prev[:n]...), line[tab+1:]...)
		bodies = append(bodies, body)
		prev = body
	}
}
